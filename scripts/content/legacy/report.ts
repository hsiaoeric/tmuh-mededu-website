import type { RosterDiff, RosterEntry } from './departmentPages';

export type CountRow = readonly [label: string, value: number | string];

export type ReportData = {
  readonly mirrorName: string;
  readonly counts: readonly CountRow[];
  readonly postsByCategory: readonly CountRow[];
  readonly datesEstimated: readonly { readonly post: string; readonly title: string; readonly date: string; readonly method: string }[];
  readonly ownerInference: readonly { readonly post: string; readonly title: string; readonly owner: string }[];
  readonly audienceInference: readonly { readonly post: string; readonly title: string; readonly audiences: readonly string[] }[];
  readonly images: {
    readonly dropped: readonly { readonly where: string; readonly src: string; readonly reason: string }[];
    readonly generatedAlts: readonly { readonly where: string; readonly count: number }[];
    readonly unreferenced: readonly string[];
    readonly totalBytes: number;
  };
  readonly links: {
    readonly http: readonly { readonly where: string; readonly href: string; readonly detail: string }[];
    readonly upgraded: readonly { readonly where: string; readonly from: string; readonly href: string }[];
    readonly repaired: readonly { readonly where: string; readonly from: string; readonly href: string }[];
    readonly internal: readonly { readonly where: string; readonly from: string; readonly href: string }[];
    readonly dropped: readonly { readonly where: string; readonly from: string; readonly reason: string }[];
  };
  readonly tables: readonly { readonly where: string; readonly detail: string }[];
  readonly headings: readonly { readonly where: string; readonly detail: string }[];
  readonly posterOnly: readonly { readonly where: string; readonly title: string; readonly images: number }[];
  readonly emptyAlbums: readonly { readonly album: string; readonly title: string; readonly owner: string; readonly cover?: string; readonly redirect: string }[];
  readonly videos: {
    readonly placeholders: readonly { readonly page: string; readonly youtubeId: string; readonly title: string }[];
    readonly ownerConflicts: readonly { readonly youtubeId: string; readonly title: string; readonly kept: string; readonly also: readonly string[] }[];
  };
  readonly downloads: {
    readonly copied: readonly { readonly label: string; readonly path: string; readonly bytes: number }[];
    readonly missing: readonly { readonly label: string; readonly href: string; readonly reason: string }[];
    readonly emptyGroups: readonly string[];
  };
  readonly emptyPages: readonly string[];
  readonly skippedContent: readonly string[];
  readonly roster: { readonly legacy: readonly RosterEntry[]; readonly diff: RosterDiff };
  readonly personalData: readonly { readonly where: string; readonly title: string; readonly note: string }[];
};

function escapeCell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function table(header: readonly string[], rows: readonly (readonly (string | number)[])[]): string {
  if (rows.length === 0) return '_None._\n';
  const lines = [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => escapeCell(String(cell))).join(' | ')} |`),
  ];
  return `${lines.join('\n')}\n`;
}

function list(items: readonly string[]): string {
  return items.length === 0 ? '_None._\n' : `${items.map((item) => `- ${item}`).join('\n')}\n`;
}

function formatRoster(entry: RosterEntry): string {
  return [entry.name, entry.ext === undefined ? '' : `#${entry.ext}`, entry.email ?? ''].filter(Boolean).join(' ');
}

/** Renders the import report. Deterministic: no timestamps or absolute paths. */
export function renderReport(data: ReportData): string {
  const sections: string[] = [];
  sections.push(`# 舊站匯入報告（Legacy import report）

由 \`npm run content:import-legacy\` 自 wget 鏡像 \`${data.mirrorName}\` 產生；請勿手動編輯，重新執行匯入即會覆寫。
Generated by \`npm run content:import-legacy\` from the wget mirror \`${data.mirrorName}\`. Do not edit by hand.

The mirror is read as data only. Nothing in it is executed, and no old-site host is contacted.
`);
  sections.push(`## Counts\n\n${table(['Item', 'Count'], data.counts)}`);
  sections.push(`## Posts by category\n\n${table(['Channel / category', 'Posts'], data.postsByCategory)}`);
  sections.push(`## Estimated publication dates

Center articles on the old site carried no date. The importer uses, in order: a ROC date in the title
(\`1130702\` → 2024-07-02), an upload timestamp in an image file name, or the latest date among
lower-numbered articles (the old ids were assigned in creation order). Review these before relying on
date order.

${table(['Post', 'Title', 'Date', 'Method'], data.datesEstimated.map((row) => [row.post, row.title, row.date, row.method]))}`);
  sections.push(`## Owners inferred from title tags

Announcements and honors default to the department; a title tag such as \`#教發中心\` or
\`【全人中心】\` assigns the center instead (\`LEGACY_TITLE_OWNER_TAGS\` in the taxonomy).

${table(['Post', 'Title', 'Owner'], data.ownerInference.map((row) => [row.post, row.title, row.owner]))}`);
  sections.push(`## Audiences inferred from title tags

${table(['Post', 'Title', 'Programs'], data.audienceInference.map((row) => [row.post, row.title, row.audiences.join(', ')]))}`);
  sections.push(`## Images

Converted images total ${(data.images.totalBytes / 1024 / 1024).toFixed(2)} MiB under \`public/assets/legacy/\`.

### Dropped, missing, or external images

These were not imported. External images were not fetched; old-site files absent from the mirror
cannot be recovered offline.

${table(['Where', 'Source', 'Reason'], data.images.dropped.map((row) => [row.where, row.src, row.reason]))}
### Generated alt text

Images whose old alt text was empty or generic received \`<title> — 圖 n\`. Replace these with real
descriptions in the CMS where the image carries information (posters, award lists).

${table(['Where', 'Images'], data.images.generatedAlts.map((row) => [row.where, row.count]))}
### Mirror images not referenced by imported content

${list(data.images.unreferenced)}`);
  sections.push(`## Links

### Plain http links kept

No HTTPS upgrade is recorded for these hosts in \`scripts/content/legacy/https-upgrades.json\`
(run the importer with \`--probe-https\` to refresh it). They stay \`http://\` links.

${table(['Where', 'Link', 'Probe'], data.links.http.map((row) => [row.where, row.href, row.detail]))}
### Upgraded to https

${table(['Where', 'Old', 'New'], data.links.upgraded.map((row) => [row.where, row.from, row.href]))}
### Repaired

${table(['Where', 'Old', 'New'], data.links.repaired.map((row) => [row.where, row.from, row.href]))}
### Old-site links rewritten to new paths

${table(['Where', 'Old', 'New'], data.links.internal.map((row) => [row.where, row.from, row.href]))}
### Dropped (anchor text kept)

${table(['Where', 'Old', 'Reason'], data.links.dropped.map((row) => [row.where, row.from, row.reason]))}`);
  sections.push(`## Tables with merged cells or truncation

Merged cells are expanded with empty cells so columns stay aligned.

${table(['Where', 'Detail'], data.tables.map((row) => [row.where, row.detail]))}`);
  sections.push(`## Headings kept as paragraphs

Heading blocks hold plain text only.

${table(['Where', 'Detail'], data.headings.map((row) => [row.where, row.detail]))}`);
  sections.push(`## Poster-only posts lacking text alternatives

These bodies are images with no text blocks. Their information is only in the image; add a text
summary (or real alt text) in the CMS.

${table(['Where', 'Title', 'Images'], data.posterOnly.map((row) => [row.where, row.title, row.images]))}`);
  sections.push(`## Empty albums (skipped)

The published album contract needs at least one photo. These albums had none in the mirror; their old
URLs redirect to the owner's gallery view.

${table(['Album', 'Title', 'Owner', 'Old cover', 'Redirect'], data.emptyAlbums.map((row) => [row.album, row.title, row.owner, row.cover ?? '', row.redirect]))}`);
  sections.push(`## Videos

### Placeholder entries skipped

${table(['Page', 'YouTube id', 'Title'], data.videos.placeholders.map((row) => [row.page, row.youtubeId, row.title]))}
### Listed under more than one owner

The first owner by source priority (center and program boards before the site-wide board) keeps the video.

${table(['YouTube id', 'Title', 'Kept', 'Also listed under'], data.videos.ownerConflicts.map((row) => [row.youtubeId, row.title, row.kept, row.also.join(', ')]))}`);
  sections.push(`## Downloads

${table(['Label', 'Copied to', 'Bytes'], data.downloads.copied.map((row) => [row.label, row.path, row.bytes]))}
### Missing

${table(['Label', 'Old link', 'Reason'], data.downloads.missing.map((row) => [row.label, row.href, row.reason]))}
### Groups left empty (not imported)

${list(data.downloads.emptyGroups)}`);
  sections.push(`## Empty old pages

Old pages that rendered no content (template placeholders such as 「很抱歉！」). They still redirect.

${list(data.emptyPages)}`);
  sections.push(`## Old content intentionally not imported

${list(data.skippedContent)}`);
  sections.push(`## Administrative roster: old 行政團隊 page vs \`src/data/centers.ts\`

The old page (now \`department_info\` page \`administrative-team\`) lists:

${list(data.roster.legacy.map(formatRoster))}
Only on the old page:

${list(data.roster.diff.onlyLegacy.map(formatRoster))}
Only on the current site:

${list(data.roster.diff.onlyCurrent.map(formatRoster))}
Extension or email differs:

${table(['Name', 'Old page', 'Current site'], data.roster.diff.mismatched.map((row) => [row.name, formatRoster(row.legacy), formatRoster(row.current)]))}`);
  sections.push(`## Personal data in recruitment lists

Recruitment results (榜單、甄選結果) publish candidate names. Review whether these should remain public,
and keep names masked (○) where the old page masked them.

${table(['Where', 'Title', 'Note'], data.personalData.map((row) => [row.where, row.title, row.note]))}`);
  return `${sections.map((section) => section.trimEnd()).join('\n\n')}\n`;
}
